<?php
// ==============================================================================
// فئة الاتصال بقاعدة البيانات (Database Connection Class)
// ==============================================================================

class Database {

    // --------------------------------------------------------------------------
    // 1. بيانات ومعلومات الاتصال بالسيرفر (Connection Credentials)
    // --------------------------------------------------------------------------

    // عنوان خادم قاعدة البيانات
    private $host = "localhost";

    // اسم قاعدة البيانات المعتمدة
    private $db_name = "internship_db"; // اسم القاعدة المعتمد لديك

    // اسم المستخدم لقاعدة البيانات
    private $username = "root";

    // كلمة المرور الخاصة بقاعدة البيانات
    private $password = "";

    // كائن الاتصال العام (PDO Object)
    public $conn;

    // --------------------------------------------------------------------------
    // 2. دالة إنشاء وفتح الاتصال (getConnection Method)
    // --------------------------------------------------------------------------

    /**
     * إنشاء كائن اتصال PDO وإعداده بترميز utf8mb4 ونمط الاستثناءات
     * 
     * @return PDO|null يعيد كائن الاتصال عند النجاح أو null عند الفشل
     */
    public function getConnection() {
        // تصفير قيمة الاتصال مسبقاً قبل أي محاولة
        $this->conn = null;

        try {
            // إنشاء اتصال PDO جديد باستخدام بيانات الخادم واسم القاعدة
            $this->conn = new PDO(
                "mysql:host=" . $this->host . ";dbname=" . $this->db_name, 
                $this->username, 
                $this->password
            );

            // ضبط ترميز الاتصال لدعم اللغة العربية والرموز التعبيرية بالكامل
            $this->conn->exec("set names utf8mb4");

            // تفعيل نمط رمي الاستثناءات عند حدوث أي خطأ في استعلامات SQL
            $this->conn->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);

        } catch(PDOException $exception) {
            // إرجاع قيمة null في حال فشل الاتصال دون إظهار الخطأ للمستخدم
            return null;
        }

        // إرجاع كائن الاتصال الجاهز للاستخدام
        return $this->conn;
    }
}
?>